# Shared factory state (LangGraph node read/write target)
# ---------------------------------------------------------------------------


class FactoryState(BaseModel):
    """Single source of truth shared across all LangGraph nodes."""

    model_config = ConfigDict(extra="forbid", arbitrary_types_allowed=True)

    request_id: str = Field(default_factory=lambda: str(uuid4()))
    user_prompt: str
    phase: Phase = Phase.INGEST
    status: RunStatus = RunStatus.PENDING

    # Artifacts
    technical_spec: TechnicalSpec | None = None
    code_artifacts: dict[str, CodeArtifacts] = Field(default_factory=dict)  # module -> artifacts
    test_results: dict[str, TestResult] = Field(default_factory=dict)  # module -> results
    fix_loops: list[FixLoop] = Field(default_factory=list)
    devops_artifacts: DevOpsArtifacts | None = None

    # Communication & state
    messages: list[AgentMessage] = Field(default_factory=list)
    worktrees: dict[str, str] = Field(default_factory=dict)  # module -> worktree absolute path
    approvals: dict[str, ApprovalRecord] = Field(default_factory=dict)  # gate -> record
    retry_counts: dict[str, int] = Field(default_factory=dict)  # agent -> count
    errors: list[FactoryError] = Field(default_factory=list)

    # Telemetry
    metrics: UsageMetrics = Field(default_factory=UsageMetrics)

    # HITL resume token: set when a gate pauses the graph
    hitl_resume_token: str | None = None

    def add_message(self, message: AgentMessage) -> Self:
        self.messages.append(message)
        return self

    def increment_retry(self, agent: str) -> int:
        self.retry_counts[agent] = self.retry_counts.get(agent, 0) + 1
        return self.retry_counts[agent]

    def add_error(self, node: str, error_type: str, message: str, traceback: str | None = None) -> None:
        self.errors.append(
            FactoryError(
                node=node,
                error_type=error_type,
                message=message,
                traceback=traceback,
                retry_count=self.retry_counts.get(node, 0),
            )
        )

    @property
    def is_paused(self) -> bool:
        return self.status == RunStatus.PAUSED

    @property
    def has_errors(self) -> bool:
        return len(self.errors) > 0

    @property
    def all_tests_passed(self) -> bool:
        if not self.test_results:
            return False
        return all(r.success for r in self.test_results.values())

    @property
    def all_gates_approved(self) -> bool:
        return all(a.status == ApprovalStatus.APPROVED for a in self.approvals.values())


