"""Core state models for the Agentic Software Factory.

Defines Pydantic models for every artifact that flows through the LangGraph
orchestration layer, plus the shared `FactoryState` TypedDict used by graph
nodes.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Literal, Self
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field, model_validator


class Phase(str, Enum):
    """Workflow execution phases."""

    INGEST = "ingest"
    PM = "pm"
    HITL_ARCHITECTURE = "hitl_architecture"
    CODER = "coder"
    QA = "qa"
    HITL_PREMERGE = "hitl_premerge"
    DEVOPS = "devops"
    HITL_DEPLOY = "hitl_deploy"
    FINALIZE = "finalize"
    ERROR = "error"
    COMPLETED = "completed"
    FAILED = "failed"


class ApprovalStatus(str, Enum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"
    TIMEOUT = "timeout"


class RunStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    PAUSED = "paused"
    COMPLETED = "completed"
    FAILED = "failed"


# ---------------------------------------------------------------------------
# Artifact models
# ---------------------------------------------------------------------------


class UserStory(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str = Field(default_factory=lambda: str(uuid4()))
    title: str
    description: str
    acceptance_criteria: list[str] = Field(default_factory=list)
    priority: Literal["low", "medium", "high", "critical"] = "medium"
    module: Literal["frontend", "backend", "database", "infra"] = "backend"


class ArchitecturePlan(BaseModel):
    model_config = ConfigDict(extra="forbid")

    overview: str
    components: list[str]
    data_flow: str
    tech_stack: dict[str, str]
    diagram_text: str | None = Field(default=None, description="Mermaid/plantuml diagram")


class TechnicalSpec(BaseModel):
    """Product Manager output: full technical specification."""

    model_config = ConfigDict(extra="forbid")

    spec_id: str = Field(default_factory=lambda: str(uuid4()))
    title: str
    summary: str
    user_stories: list[UserStory] = Field(default_factory=list)
    architecture: ArchitecturePlan
    acceptance_criteria: list[str] = Field(default_factory=list)
    non_functional_requirements: list[str] = Field(default_factory=list)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class CodeArtifact(BaseModel):
    """A single file generated by the Coder agent."""

    model_config = ConfigDict(extra="forbid")

    path: str  # relative path within the module worktree
    content: str
    language: str
    module: Literal["frontend", "backend", "database", "infra"]
    description: str = ""


class CodeArtifacts(BaseModel):
    """All code artifacts for a module, keyed by relative path."""

    model_config = ConfigDict(extra="forbid")

    module: Literal["frontend", "backend", "database", "infra"]
    files: dict[str, CodeArtifact] = Field(default_factory=dict)

    def add(self, artifact: CodeArtifact) -> Self:
        self.files[artifact.path] = artifact
        return self


class TestCase(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str = Field(default_factory=lambda: str(uuid4()))
    name: str
    file_path: str
    test_type: Literal["unit", "integration", "e2e"] = "unit"
    content: str
    status: Literal["pending", "passed", "failed", "errored"] = "pending"
    error_message: str | None = None
    duration_ms: float | None = None


class TestResult(BaseModel):
    """QA agent output: test suite results."""

    model_config = ConfigDict(extra="forbid")

    suite_id: str = Field(default_factory=lambda: str(uuid4()))
    module: Literal["frontend", "backend", "database", "infra"]
    test_cases: list[TestCase] = Field(default_factory=list)
    total: int = 0
    passed: int = 0
    failed: int = 0
    errored: int = 0
    success: bool = False
    output: str = ""
    executed_at: datetime | None = None

    @model_validator(mode="after")
    def _compute_totals(self) -> Self:
        self.total = len(self.test_cases)
        self.passed = sum(1 for t in self.test_cases if t.status == "passed")
        self.failed = sum(1 for t in self.test_cases if t.status == "failed")
        self.errored = sum(1 for t in self.test_cases if t.status == "errored")
        self.success = self.failed == 0 and self.errored == 0 and self.total > 0
        return self


class FixLoop(BaseModel):
    """A single self-healing fix iteration."""

    model_config = ConfigDict(extra="forbid")

    iteration: int
    failure_summary: str
    fix_applied: str
    files_changed: list[str]
    resolved: bool = False


class DevOpsArtifacts(BaseModel):
    """DevOps agent output: Docker, CI/CD, deployment manifests."""

    model_config = ConfigDict(extra="forbid")

    dockerfile: str | None = None
    docker_compose: str | None = None
    github_actions_ci: str | None = None
    deployment_script: str | None = None
    k8s_manifests: str | None = None
    env_example: str | None = None
    readme: str | None = None


class ApprovalRecord(BaseModel):
    """Human-in-the-loop approval gate record."""

    model_config = ConfigDict(extra="forbid")

    gate: Literal["architecture", "premerge", "deploy"]
    status: ApprovalStatus = ApprovalStatus.PENDING
    reviewer: str | None = None
    comments: str = ""
    requested_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    decided_at: datetime | None = None


class FactoryError(BaseModel):
    model_config = ConfigDict(extra="forbid")

    node: str
    error_type: str
    message: str
    traceback: str | None = None
    occurred_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    retry_count: int = 0


